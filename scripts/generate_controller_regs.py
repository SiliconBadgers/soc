#!/usr/bin/env python3
"""Generate the selected controller CSR configuration from SystemRDL."""

import argparse
import hashlib
import importlib.metadata
import json
import tempfile
from pathlib import Path

from peakrdl_cheader.exporter import CHeaderExporter
from peakrdl_regblock import RegblockExporter
from peakrdl_regblock.cpuif.passthrough import PassthroughCpuif
from peakrdl_regblock.udps import ALL_UDPS
from systemrdl import RDLCompiler
from systemrdl.node import RegNode

ROOT = Path(__file__).resolve().parents[1]
VERSIONS = json.loads((ROOT / "dependencies.json").read_text())["tools"]["controller_generators"]


def generate(output, payload_width, counter_width):
    """Write deterministic RTL, software definitions, and their input manifest."""
    actual = {name: importlib.metadata.version(name) for name in VERSIONS}
    if actual != VERSIONS:
        raise ValueError(f"Generator versions differ from the lock: {actual}")
    output.mkdir(parents=True, exist_ok=True)
    source = ROOT / "regs/controller.rdl"
    access_functions = []
    offsets = []
    fields = []
    for view in ("host", "firmware"):
        compiler = RDLCompiler()
        for udp in ALL_UDPS:
            compiler.register_udp(udp)
        compiler.compile_file(str(source), defines={"FIRMWARE": "1"} if view == "firmware" else {})
        root = compiler.elaborate(
            "controller",
            inst_name=f"controller_{view}",
            parameters={"PAYLOAD_WORDS": payload_width // 32, "COUNTER_WIDTH": counter_width},
        )
        RegblockExporter().export(
            root,
            str(output),
            cpuif_cls=PassthroughCpuif,
            module_name=f"controller_{view}",
            package_name=f"controller_{view}_pkg",
            default_reset_activelow=True,
            default_reset_async=True,
            address_width=12,
            err_if_bad_addr=True,
            err_if_bad_rw=True,
        )
        layout_header = output / f"controller_{view}.h"
        CHeaderExporter().export(root, str(layout_header), reuse_typedefs=False)
        layout_header.write_text(
            "/* Layout description only. Packed members can compile to byte accesses.\n"
            " * Use controller_regs.h scalar accessors for hardware MMIO. */\n"
            + layout_header.read_text()
        )
        lines = [
            f"  function automatic logic [31:0] {view}_write_mask(input logic [31:0] address);",
            "    case (address)",
        ]
        for node in root.top.descendants(unroll=True):
            if isinstance(node, RegNode):
                if view == "host":
                    name = node.get_path().split(".", 1)[1]
                    name = name.replace("[", "_").replace("]", "").replace(".", "_").upper()
                    offsets.append(
                        f"#define CONTROLLER_{name}_OFFSET 0x{node.absolute_address:03x}u"
                    )
                    for field in node.fields():
                        prefix = f"CONTROLLER_{name}_{field.inst_name.upper()}"
                        mask = ((1 << field.width) - 1) << field.low
                        fields += [
                            f"#define {prefix}_MASK 0x{mask:08x}u",
                            f"#define {prefix}_SHIFT {field.low}u",
                            f"#define {prefix}_WIDTH {field.width}u",
                        ]
                mask = sum(
                    ((1 << field.width) - 1) << field.low
                    for field in node.fields()
                    if field.is_sw_writable
                )
                lines.append(f"      32'h{node.absolute_address:08x}: return 32'h{mask:08x};")
        lines += ["      default: return '0;", "    endcase", "  endfunction"]
        access_functions.extend(lines)
    (output / "controller_access_pkg.sv").write_text(
        "// Generated write masks for wrapper validation.\npackage controller_access_pkg;\n"
        + "\n".join(access_functions)
        + "\nendpackage\n"
    )
    (output / "controller_config_pkg.sv").write_text(
        "// Generated by scripts/generate_controller_regs.py.\n"
        "package controller_config_pkg;\n"
        f"  localparam int unsigned PayloadWidth = {payload_width};\n"
        f"  localparam int unsigned CounterWidth = {counter_width};\n"
        "endpackage\n"
    )
    (output / "controller_regs.h").write_text(
        "/* Generated controller MMIO interface. */\n"
        "#ifndef CONTROLLER_REGS_H\n#define CONTROLLER_REGS_H\n"
        "#include <stdint.h>\n"
        f"#define CONTROLLER_PAYLOAD_WIDTH {payload_width}u\n"
        f"#define CONTROLLER_COUNTER_WIDTH {counter_width}u\n"
        + "\n".join(offsets + fields)
        + "\n\n"
        "/* base and offset must be four-byte aligned. Offsets are byte offsets.\n"
        " * Each accessor performs one volatile 32-bit transfer. Platform MMIO\n"
        " * ordering operations remain the caller's responsibility. */\n"
        "static inline uint32_t controller_read32(uintptr_t base, uint32_t offset)\n"
        "{\n"
        "    return *(volatile const uint32_t *)(base + offset);\n"
        "}\n\n"
        "static inline void controller_write32(uintptr_t base, uint32_t offset, uint32_t value)\n"
        "{\n"
        "    *(volatile uint32_t *)(base + offset) = value;\n"
        "}\n"
        "#endif\n"
    )
    files = sorted(path for path in output.iterdir() if path.suffix in (".sv", ".h"))
    manifest = {
        "schema": 1,
        "payload_width": payload_width,
        "counter_width": counter_width,
        "versions": actual,
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "files": {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in files},
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "generated/controller")
    parser.add_argument("--payload-width", type=int, default=128)
    parser.add_argument("--counter-width", type=int, default=16)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not (32 <= args.payload_width <= 1792 and args.payload_width % 32 == 0):
        parser.error("--payload-width must be a multiple of 32 from 32 through 1792")
    if not 2 <= args.counter_width <= 32:
        parser.error("--counter-width must be from 2 through 32")
    if args.check:
        with tempfile.TemporaryDirectory(prefix="controller-regs-") as directory:
            temporary = Path(directory)
            generate(temporary, args.payload_width, args.counter_width)
            expected = {path.name: path.read_bytes() for path in temporary.iterdir()}
            actual = (
                {path.name: path.read_bytes() for path in args.out.iterdir()}
                if args.out.is_dir()
                else {}
            )
            if actual != expected:
                parser.exit(1, f"Generated controller files differ: {args.out}\n")
    else:
        generate(args.out, args.payload_width, args.counter_width)
    print(f"Controller CSRs: {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
